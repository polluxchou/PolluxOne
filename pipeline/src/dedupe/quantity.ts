/**
 * 「量」：一个**数值**加一个**量纲**——⑤ 判冲突时唯一该比的东西。
 *
 * 为什么不能直接用 ④ 的 `numericSignature`：那个签名是「数字 + 紧跟的最多
 * 两个字」，它把**数值**和**后面的正文**糅在同一个 token 里。实跑时
 * 「3 月 15 日生效」拿到 `15日生`、「3 月 15 日起生效」拿到 `15日起`——
 * 没有任何一个数字不同，只是行文不同，可两个 token 互不相等，⑤ 就把这
 * 两句同义的话判成矛盾。`numericSignature` 在 ④ 里是对的（签名不等就不
 * 归并，宁可少归并），但拿它当「矛盾」的判据是把「写法不同」读成了
 * 「说法不同」。
 *
 * 所以这里换一套表示：**数值归一到精确十进制串，量纲归一到一个字符**。
 * 两条 claim 只有在**同一个量纲上给出了不同的值**时才算数字打架。
 *
 * ## 两个方向的取舍
 *
 * 归一得越狠，「同值不同写法」越不会被误杀，但两个**真的不同**的量被折成
 * 一个的风险也越大——那是漏检，播出去两个打架的数字而没人看得见。所以：
 *
 * - **数值**放开归一：`1.5`/`1.50`、`2,800`/`2800`、`1 万亿`/`10000 亿`
 *   都是同一个数，这是可证的等值，折叠它们不会让任何真分歧溜过去。
 * - **量纲**只收一个字符，且只认一条别名（`号`→`日`）。宁可把
 *   `公里`/`千米` 这种同义单位判成两个量纲（误杀，稿子变空，用户看得见），
 *   也不把 `美元`/`欧元` 折成一个（漏检，用户看不见）。
 */

/**
 * 量纲只吃**一个**字符：紧跟数值（和数量级）的第一个非数字、非空白、非标点字符。
 *
 * **已知歧义**：`\d{1,3}(?:,\d{3})+` 认千分位，而 NFKC 会把全角逗号折成半角，
 * 于是「排名第 3，250 名选手参赛」里那个句读逗号会被读成千分位，取出 3250。
 * 留着它是因为中文排版里全角千分位（「２，８００万欧元」）是真的在用，而误判
 * 要凑齐「1–3 位数 + 逗号 + 恰好 3 位数」这个形状。方向也站得住：misparse
 * 出来的值和对家对不上，落在**误杀**一侧（稿子变空，用户看得见），不是漏检。
 */
const QUANTITY =
  /(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?)\s*([万亿]*)\s*((?:[%‰]|[^\d\s\p{P}])?)/gu;

/**
 * 只有 `万`/`亿` 算数量级。
 *
 * `十`/`百`/`千` 刻意不算：`千米`、`百分点`、`十字路口` 里它们是单位或词的
 * 一部分，当成数量级会把 `31.4 千米` 读成 31400 米。漏认一个数量级只是让
 * 两种写法不再等值（误杀方向），错认一个数量级会凭空改掉数值本身。
 */
const SCALE_ZEROS: Record<string, number> = { 万: 4, 亿: 8 };

/**
 * 量纲别名。**刻意只有一条**：`3 月 15 号` 和 `3 月 15 日` 是同一天，中文媒体
 * 两种都写。每加一条别名就是承认两个不同的字是同一个量纲——加错了就是漏检，
 * 所以这张表只收「同一个所指、不可能指不同东西」的对子。
 */
const DIM_ALIASES: Record<string, string> = { 号: "日" };

/**
 * 把 `raw`（可能带千分位和小数点）的小数点右移 `zeros` 位，得到**精确**的
 * 十进制规范串。
 *
 * 用字符串而不是 `Number`：`0.1 亿` 在浮点里是 10000000.000000002，和
 * `1000 万` 的 10000000 不相等，于是两条说同一个数的 claim 会被判成矛盾。
 * 这类误差没有阈值能挡，只能不产生它。
 */
function shiftDecimal(raw: string, zeros: number): string {
  const [intPart = "0", fracPart = ""] = raw.replace(/,/g, "").split(".");
  const pointPos = intPart.length + zeros;
  const digits = (intPart + fracPart).padEnd(pointPos, "0");
  const int = digits.slice(0, pointPos).replace(/^0+(?=\d)/, "");
  const frac = digits.slice(pointPos).replace(/0+$/, "");
  return frac ? `${int}.${frac}` : int;
}

/**
 * 一句话里的全部「量」，每个编码成 `值\0量纲`，排序后返回（可含重复）。
 *
 * 取量之前先 `NFKC` + 去零宽：`\d` 只认 ASCII 数字，而中文媒体用全角数字
 * 不罕见。不归一的话「约 ２３ 亿美元」取不出任何量，和「约 31 亿美元」比
 * 就是「空集 ⊆ 任意集」——**既不归并也不报冲突，一个真的数字分歧就这么
 * 悄无声息地播出去了**。这是这条流水线唯一不能犯的错。
 *
 * **仍然认不出中文数字**（「一万亿元」取不出量，见 `shingle.normalize` 的
 * 同名局限）。这就是下面 `isSubMultiset` 那个残留风险的来源。
 */
export function quantities(text: string): string[] {
  const clean = text.normalize("NFKC").replace(/[​-‍﻿]/gu, "");
  return [...clean.matchAll(QUANTITY)]
    .map((m) => {
      const zeros = [...(m[2] ?? "")].reduce((sum, c) => sum + (SCALE_ZEROS[c] ?? 0), 0);
      const dim = m[3] ?? "";
      return `${shiftDecimal(m[1]!, zeros)}\0${DIM_ALIASES[dim] ?? dim}`;
    })
    .sort();
}
